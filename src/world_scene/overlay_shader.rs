use fyrox::{
    asset::untyped::ResourceKind,
    material::shader::{ShaderResource, ShaderResourceExtension},
};
use uuid::Uuid;

/// Shader d'une surcouche translucide non éclairée : il affiche la texture RGBA telle quelle,
/// mélangée à ce qui est derrière, sans écrire dans le tampon de profondeur.
const SOURCE: &str = r##"
(
    name: "WaterOverlayShader",
    resources: [
        (
            name: "diffuseTexture",
            kind: Texture(kind: Sampler2D, fallback: White),
            binding: 0
        ),
        (
            name: "fyrox_instanceData",
            kind: PropertyGroup([
                // Autogenerated
            ]),
            binding: 1
        ),
        (
            name: "fyrox_cameraData",
            kind: PropertyGroup([
                // Autogenerated
            ]),
            binding: 2
        ),
    ],
    disabled_passes: ["GBuffer", "DirectionalShadow", "PointShadow", "SpotShadow"],
    passes: [
        (
            name: "Forward",
            draw_parameters: DrawParameters(
                cull_face: None,
                color_write: ColorMask(red: true, green: true, blue: true, alpha: true),
                depth_write: false,
                stencil_test: None,
                depth_test: Some(Less),
                blend: Some(BlendParameters(
                    func: BlendFunc(
                        sfactor: SrcAlpha,
                        dfactor: OneMinusSrcAlpha,
                        alpha_sfactor: SrcAlpha,
                        alpha_dfactor: OneMinusSrcAlpha,
                    ),
                    equation: BlendEquation(rgb: Add, alpha: Add)
                )),
                stencil_op: StencilOp(
                    fail: Keep,
                    zfail: Keep,
                    zpass: Keep,
                    write_mask: 0xFFFF_FFFF,
                ),
                scissor_box: None
            ),
            vertex_shader:
               r#"
                layout(location = 0) in vec3 vertexPosition;
                layout(location = 1) in vec2 vertexTexCoord;

                out vec2 texCoord;

                void main()
                {
                    gl_Position = fyrox_instanceData.worldViewProjection * vec4(vertexPosition, 1.0);
                    texCoord = vertexTexCoord;
                }
               "#,
            fragment_shader:
               r#"
                out vec4 FragColor;

                in vec2 texCoord;

                void main()
                {
                    FragColor = S_SRGBToLinear(texture(diffuseTexture, texCoord));
                }
               "#,
        ),
    ],
)
"##;

pub(super) fn shader() -> ShaderResource {
    ShaderResource::from_str(Uuid::now_v7(), SOURCE, ResourceKind::Embedded)
        .expect("shader de surcouche valide")
}
